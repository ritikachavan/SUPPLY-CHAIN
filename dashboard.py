"""
Streamlit KPI dashboard for the Supply Chain Delay Risk Predictor.

Run with:
    streamlit run dashboard.py

Shows:
- overall late-delivery rate KPIs
- late-delivery rate by shipping mode / region / market
- Random Forest feature-importance chart
- a risk-score lookup: shipping mode + region + category -> P(late)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import joblib
import pandas as pd
import plotly.express as px
import streamlit as st

sys.path.insert(0, str(Path(__file__).resolve().parent))

from src.config import (  # noqa: E402
    CATEGORY_COL,
    IMPORTANCE_PATH,
    META_PATH,
    METRICS_PATH,
    MODEL_PATH,
    REGION_COL,
    SEGMENT_RATES_PATH,
    SHIPPING_MODE_COL,
    SCHEDULED_DAYS_COL,
    TARGET_COL,
)

st.set_page_config(
    page_title="Supply Chain Delay Risk Predictor",
    page_icon="🚚",
    layout="wide",
)

# Colours reused across charts ------------------------------------------------
BAR_COLOR = "#d9534f"
ACCENT = "#1f77b4"


# --------------------------------------------------------------------------- #
# Loaders (cached — files are regenerated by `python run_pipeline.py`)
# --------------------------------------------------------------------------- #
@st.cache_data
def load_segment_rates() -> pd.DataFrame:
    return pd.read_csv(SEGMENT_RATES_PATH)


@st.cache_data
def load_feature_importance() -> pd.DataFrame:
    return pd.read_csv(IMPORTANCE_PATH)


@st.cache_data
def load_json(path: Path) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


@st.cache_resource
def load_models() -> dict:
    return joblib.load(MODEL_PATH)


@st.cache_resource
def load_meta() -> dict:
    return load_json(META_PATH)


def risk_band(prob: float) -> tuple[str, str]:
    """Map a late-delivery probability to a labelled risk band + colour."""
    if prob >= 0.60:
        return "🔴 HIGH", "#d9534f"
    if prob >= 0.40:
        return "🟠 MEDIUM", "#f0ad4e"
    return "🟢 LOW", "#5cb85c"


def predict_late_probability(shipping_mode: str, region: str, category: str,
                             scheduled_days: float) -> float:
    """Rebuild one encoded feature row and ask the Random Forest for P(late)."""
    model, meta = load_models(), load_meta()

    # Start from training-set defaults, then override the chosen inputs.
    row: dict = dict(meta["defaults"])
    row[SHIPPING_MODE_COL] = shipping_mode
    row[REGION_COL] = region
    row[CATEGORY_COL] = category
    row[SCHEDULED_DAYS_COL] = float(scheduled_days)

    # Re-encode exactly like training, then align to the training columns.
    X = pd.get_dummies(pd.DataFrame([row]),
                       columns=meta["categorical_features"], dtype=int)
    X = X.reindex(columns=meta["feature_columns"], fill_value=0)

    return float(model["Random Forest"].predict_proba(X)[0, 1])


# --------------------------------------------------------------------------- #
# Page
# --------------------------------------------------------------------------- #
st.title("🚚 Supply Chain Delay Risk Predictor")
st.caption("DataCo Smart Supply Chain dataset · 180k orders · "
           "predicts whether an order ships later than promised")

try:
    rates = load_segment_rates()
    importance = load_feature_importance()
    metrics = load_json(METRICS_PATH)
    meta = load_meta()
except (FileNotFoundError, json.JSONDecodeError):
    st.error("Artifacts not found. Run `python run_pipeline.py` first, "
             "then refresh this page.")
    st.stop()

target_stats = meta["target_stats"]
overall_rate = target_stats["late_rate"]
rf_metrics = metrics["models"]["Random Forest"]

# --- KPI row ----------------------------------------------------------------
k1, k2, k3, k4 = st.columns(4)
k1.metric("Overall late-delivery rate", f"{overall_rate:.1%}")
k2.metric("Orders analysed", f"{target_stats['rows']:,}")
k3.metric("Random Forest accuracy", f"{rf_metrics['accuracy']:.1%}")
k4.metric("Random Forest F1", f"{rf_metrics['f1']:.3f}")

st.divider()

# --- Late rate by shipping mode / region ------------------------------------
left, right = st.columns(2)

mode_rates = rates[rates["dimension"] == "Shipping mode"].sort_values(
    "late_rate", ascending=True)
with left:
    st.subheader("Late-delivery rate by shipping mode")
    fig = px.bar(mode_rates, x="late_rate", y="segment", orientation="h",
                 text="late_rate", color_discrete_sequence=[BAR_COLOR])
    fig.update_traces(texttemplate="%{text:.1f}%", textposition="outside")
    fig.update_layout(xaxis_title="Late-delivery rate (%)",
                      yaxis_title="", height=380,
                      xaxis_range=[0, 110], showlegend=False)
    st.plotly_chart(fig, width="stretch")

region_rates = (rates[rates["dimension"] == "Region"]
                .sort_values("late_rate", ascending=True).tail(12))
with right:
    st.subheader("Late-delivery rate by region (top 12)")
    fig = px.bar(region_rates, x="late_rate", y="segment", orientation="h",
                 text="late_rate", color_discrete_sequence=[ACCENT])
    fig.update_traces(texttemplate="%{text:.1f}%", textposition="outside")
    fig.update_layout(xaxis_title="Late-delivery rate (%)",
                      yaxis_title="", height=380,
                      xaxis_range=[0, 70], showlegend=False)
    st.plotly_chart(fig, width="stretch")

st.divider()

# --- Feature importance -----------------------------------------------------
fi_left, fi_right = st.columns([3, 2])

with fi_left:
    st.subheader("What drives late delivery? (Random Forest importance)")
    top_imp = importance.head(10).sort_values("importance", ascending=True)
    fig = px.bar(top_imp, x="importance", y="feature", orientation="h",
                 text="importance", color_discrete_sequence=["#5bc0de"])
    fig.update_traces(texttemplate="%{text:.3f}", textposition="outside")
    fig.update_layout(xaxis_title="Importance (Gini)", yaxis_title="",
                      height=420, showlegend=False)
    st.plotly_chart(fig, width="stretch")

with fi_right:
    st.subheader("Model comparison (test set)")
    comp = pd.DataFrame({
        name: {k: v for k, v in m.items() if k in
               ("accuracy", "precision", "recall", "f1")}
        for name, m in metrics["models"].items()
    }).T
    st.dataframe(comp.style.format("{:.4f}"), width="stretch")

    st.subheader("Top 3 bottleneck segments")
    bottlenecks = pd.read_csv(
        Path(__file__).resolve().parent / "outputs" / "bottlenecks.csv")
    for i, row in bottlenecks.iterrows():
        st.write(f"**{i + 1}. {row['dimension']}: {row['segment']}** — "
                 f"{row['late_rate']:.1f}% late ({row['orders']:,} orders)")

st.divider()

# --- Risk score lookup ------------------------------------------------------
st.subheader("🎯 Risk-score lookup")
st.write("Pick a **shipping mode + region + product category** to get the "
         "model's predicted probability that the order ships late.")

cats = sorted(rates[rates["dimension"] == "Product category"]["segment"])
regions = sorted(rates[rates["dimension"] == "Region"]["segment"])
modes = sorted(rates[rates["dimension"] == "Shipping mode"]["segment"])

c1, c2, c3, c4 = st.columns(4)
shipping_mode = c1.selectbox("Shipping mode", modes,
                             index=modes.index("First Class"))
region = c2.selectbox("Region", regions, index=regions.index("Western Europe"))
category = c3.selectbox("Product category", cats, index=cats.index("Cameras"))
scheduled_days = c4.slider(SCHEDULED_DAYS_COL, min_value=0, max_value=6,
                           value=4, step=1,
                           help="Promised shipping time in days")

prob = predict_late_probability(shipping_mode, region, category,
                                float(scheduled_days))
band, _colour = risk_band(prob)

r1, r2, r3 = st.columns(3)
r1.metric("Predicted late-delivery probability", f"{prob:.1%}")
r2.metric("Risk band", band)
r3.metric("vs. overall rate", f"{prob - overall_rate:+.1%} pts",
          delta_color="inverse")

st.progress(min(prob, 1.0),
            text=f"P(late) = {prob:.1%} for "
                 f"{shipping_mode} → {region} → {category}")
st.caption("Other inputs (market, payment type, order date, …) are filled "
           "with their training-set median/mode values.")

st.divider()
st.caption("Built with Streamlit · model artifacts from `python run_pipeline.py`")

